const SPRC={};
function buildSprite(rows,pal){
  const w=rows[0].length,h=rows.length;const c=document.createElement('canvas');c.width=w;c.height=h;const g=c.getContext('2d');
  for(let y=0;y<h;y++)for(let x=0;x<w;x++){const ch=rows[y][x];if(ch==='.')continue;g.fillStyle=pal[ch]||PAL[ch]||'#f0f';g.fillRect(x,y,1,1);}
  return c;
}
function silhouette(src,col){const c=document.createElement('canvas');c.width=src.width;c.height=src.height;const g=c.getContext('2d');g.drawImage(src,0,0);g.globalCompositeOperation='source-in';g.fillStyle=col;g.fillRect(0,0,c.width,c.height);return c;}
function flipped(src){const c=document.createElement('canvas');c.width=src.width;c.height=src.height;const g=c.getContext('2d');g.translate(src.width,0);g.scale(-1,1);g.drawImage(src,0,0);return c;}
